#!/bin/bash
# 两个生成器共用的 JSON 字符串转义。用 `. lib.sh` 引入。
#
# ⚠️ 不用 awk 做这件事：这里要转义的东西是 `\` 和 `"` 本身，写进 awk 程序就是四层
# 引号嵌套，实际很容易退化成一条静默的空字符串（正文整段消失且不报错）。
# bash 的参数展开没有这层转义。

# 从 stdin 读，写到 stdout。
json_escape() {
  local s
  s=$(cat)
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  s=${s//$'\t'/\\t}
  s=${s//$'\r'/}
  s=${s//$'\n'/\\n}
  printf '%s' "$s"
}
